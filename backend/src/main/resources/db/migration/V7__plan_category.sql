-- 계획의 목적 분류 (v0.23.0).
-- 계획 초안을 만드는 LLM 호출이 카테고리를 함께 판정한다(추가 호출 없음). 지금까지는 챌린지가
-- 열릴 때 목표명을 키워드 사전으로 훑어 즉석에서 분류했고 결과가 어디에도 남지 않았다 —
-- 그래서 사전에 없는 목적은 영영 분류되지 않았고, 집계하려면 계획을 전부 읽어 다시 분류해야 했다.

-- 진실의 원본. 모델이 CATEGORIES(어학·자격증·운동·코딩·독서·글쓰기·악기·요리·재테크) 중 하나를
-- 고르고, 어디에도 맞지 않으면 값이 비어 있다(그때는 챌린지를 만들지 않는다).
ALTER TABLE plans ADD COLUMN category TEXT;

-- (category, 기간 버킷)에서 파생된 조건 키("어학:14"). challenges.condition_key와 같은 값이다.
-- [읽지 않는 쓰기 전용 투영] 애플리케이션은 이 컬럼을 SELECT하지 않는다 — Plan.conditionKey()가
-- 언제나 계산으로 답하고, 저장은 나중에 붙일 집계(GROUP BY condition_key)만을 위한 것이다.
-- 매 저장마다 다시 계산돼 기록되므로 기간이 바뀌어도(이월로 하루 연장) 동기화 코드 없이 맞는다.
ALTER TABLE plans ADD COLUMN condition_key TEXT;

-- [백필하지 않는다] SQL로는 자바 분류기를 돌릴 수 없다. 기존 행은 NULL로 남고 다음 저장 때
-- 채워진다. 이미 고정된 계획의 씨앗은 challenge_seeds에 등록돼 있어 챌린지 동작에는 영향이 없다.
-- [인덱스도 만들지 않는다] 아직 이 컬럼을 읽는 질의가 하나도 없다 — 집계를 넣는 커밋에서 함께 만든다.
